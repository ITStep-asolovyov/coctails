fun String.translateIngredient(): String {
    val lower = this.lowercase().trim()
    // Exact match first
    ingredientTranslations[lower]?.let { return it }
    // Partial match for compound names not in the map (try longest prefix)
    ingredientTranslations.entries
        .filter { lower.contains(it.key) }
        .maxByOrNull { it.key.length }
        ?.let { return it.value }
    return this
}

fun String.translateCategory() = categoryTranslations[this] ?: this
fun String.translateGlass() = glassTranslations[this] ?: this
fun String.translateAlcoholic() = alcoholicTranslations[this] ?: this
